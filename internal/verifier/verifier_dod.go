// Status indicates the enforcement mode of a verifier class.

func ParseBriefDoDItems(dodMD string) []BriefDoDItem {
	trimmed := strings.TrimSpace(dodMD)
	if trimmed == "" {
		return nil
	}

	// Try JSON first
	if strings.HasPrefix(trimmed, "[") {
		var jsonItems []BriefDoDItem
		if err := json.Unmarshal([]byte(trimmed), &jsonItems); err == nil && len(jsonItems) > 0 {
			return jsonItems
		}
	}

	var items []BriefDoDItem
	seen := make(map[string]bool)

	scanner := bufio.NewScanner(strings.NewReader(dodMD))
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue
		}
		var id, desc, hint string
		if m := dodItemRegex.FindStringSubmatch(line); len(m) > 1 {
			id = strings.TrimSpace(m[1])
			if len(m) > 2 {
				desc = strings.TrimSpace(m[2])
			}
		} else if m := dodFallbackRegex.FindStringSubmatch(line); len(m) > 1 {
			id = strings.TrimSpace(m[1])
			if len(m) > 2 {
				desc = strings.TrimSpace(m[2])
			}
		}
		if id != "" {
			normID := strings.ToUpper(id)
			if !seen[normID] {
				seen[normID] = true
				if hm := dodHintRegex.FindStringSubmatch(desc); len(hm) > 0 {
					for i := 1; i < len(hm); i++ {
						if hm[i] != "" {
							hint = strings.TrimSpace(hm[i])
							break
						}
					}
					desc = strings.TrimSpace(dodHintRegex.ReplaceAllString(desc, ""))
				}
				desc = strings.Trim(desc, "*_` \t")
				items = append(items, BriefDoDItem{
					ID:           id,
					Description:  desc,
					VerifierHint: hint,
				})
			}
		}
	}
	return items
}

// IsMechanicallyVerifiedEvidence checks whether the given evidence string contains
// an authentic mechanical verification anchor or log SHA reference rather than unverified self-report prose (#648).
func IsMechanicallyVerifiedEvidence(evidence string, rawLogSHA string) bool {
	trimmed := strings.TrimSpace(evidence)
	if trimmed == "" {
		return false
	}
	lower := strings.ToLower(trimmed)

	// Banned bare words, phrases, and negative states that never prove criteria
	bannedExact := map[string]bool{
		"ok":                 true,
		"ok ":                true,
		"pass":               true,
		"not passed":         true,
		"failed":             true,
		"error":              true,
		"exit code 0":        true,
		"done":               true,
		"completed":          true,
		"verified":           true,
		"all good":           true,
		"test":               true,
		"tests green":        true,
		"tests passed":       true,
		"unit test passed":   true,
		"met requirement":    true,
		"completed task":     true,
		"verified by worker": true,
	}
	if bannedExact[lower] {
		return false
	}

	// Reject any string containing negative pass/ok or failure indicators
	if strings.Contains(lower, "not pass") || strings.Contains(lower, "fail") || strings.Contains(lower, "error") {
		return false
	}

	// 1. Authentically bound verification evidence generated by verifier
	if strings.HasPrefix(lower, "bound to check[") || strings.HasPrefix(lower, "bound to artifact[") || strings.Contains(lower, "(verified on disk)") {
		return true
	}

	// 2. Exact match or reference to authentic rawLogSHA (minimum 8 hex characters, no bare token)
	trimmedSHA := strings.TrimSpace(rawLogSHA)
	if len(trimmedSHA) >= 8 {
		lowerSHA := strings.ToLower(trimmedSHA)
		prefix := lowerSHA[:8]
		if strings.Contains(lower, prefix) || strings.Contains(lower, lowerSHA) {
			return true
		}
	}

	return false
}

var knownCheckTypes = map[string]string{
	"gotest":     "go-test",
	"go-test":    "go-test",
	"script":     "script",
	"diffguard":  "diff-guard",
	"diff-guard": "diff-guard",
	"holdout":    "holdout",
	"canary":     "canary",
}

func isTypeOnlyHint(token string) bool {
	trimmed := strings.ToLower(strings.TrimSpace(token))
	trimmedColon := strings.TrimSuffix(trimmed, ":")
	_, ok := knownCheckTypes[trimmedColon]
	return ok
}

func canonicalCheckType(t string) (string, bool) {
	norm := strings.ToLower(strings.TrimSpace(t))
	c, ok := knownCheckTypes[norm]
	return c, ok
}

func checkTypeMatches(hintType, checkType string) bool {
	hNorm, hOk := canonicalCheckType(hintType)
	cNorm, cOk := canonicalCheckType(checkType)
	if hOk && cOk {
		return hNorm == cNorm
	}
	return strings.EqualFold(strings.TrimSpace(hintType), strings.TrimSpace(checkType))
}

func exactTargetMatch(pattern, target string) bool {
	p := strings.TrimSpace(pattern)
	t := strings.TrimSpace(target)
	if p == "" || t == "" {
		return false
	}
	if strings.EqualFold(p, t) {
		return true
	}
	cleanP := strings.TrimPrefix(filepath.Clean(filepath.ToSlash(p)), "./")
	cleanT := strings.TrimPrefix(filepath.Clean(filepath.ToSlash(t)), "./")
	if strings.EqualFold(cleanP, cleanT) {
		return true
	}
	// For multi-target strings (such as diff-guard allowed paths), match exact token
	for _, seg := range strings.Fields(t) {
		cleanSeg := strings.TrimPrefix(filepath.Clean(filepath.ToSlash(seg)), "./")
		if strings.EqualFold(cleanP, cleanSeg) {
			return true
		}
	}
	return false
}

func splitVerifierHints(hint string) []string {
	var tokens []string
	parts := strings.FieldsFunc(hint, func(r rune) bool {
		return r == ',' || r == ';'
	})
	for _, p := range parts {
		trimmed := strings.TrimSpace(p)
		if trimmed != "" {
			tokens = append(tokens, trimmed)
		}
	}
	return tokens
}

func verifyArtifactSupportingEvidence(artifactPath string, workerEvidence string, evidence TrustedEvidence) (string, error) {
	root := evidence.WorktreeDir
	if root == "" {
		root = evidence.RepoRoot
	}
	if root == "" {
		return "", fmt.Errorf("trusted root required: artifact verification cannot run without trusted worktree_dir or repo_root")
	}

	rootInfo, err := os.Stat(root)
	if err != nil || !rootInfo.IsDir() {
		return "", fmt.Errorf("trusted root %q is not an accessible directory", root)
	}

	p := strings.TrimSpace(artifactPath)
	if p == "" {
		return "", fmt.Errorf("empty artifact path")
	}

	// Reject absolute paths (both OS-native and rooted slash/backslash paths across Unix/Windows)
	if filepath.IsAbs(p) || strings.HasPrefix(p, "/") || strings.HasPrefix(p, `\`) {
		return "", fmt.Errorf("artifact path %q rejected: absolute paths outside trusted root are forbidden", p)
	}

	// Reject directory traversal (normalize backslashes and clean into forward-slash form)
	slashP := strings.ReplaceAll(filepath.ToSlash(p), `\`, "/")
	cleanSlash := filepath.ToSlash(filepath.Clean(slashP))
	if cleanSlash == "." || cleanSlash == ".." || strings.HasPrefix(cleanSlash, "../") || strings.Contains(cleanSlash, "/../") || filepath.IsAbs(cleanSlash) || strings.HasPrefix(cleanSlash, "/") {
		return "", fmt.Errorf("artifact path %q rejected: directory traversal outside trusted root is forbidden", p)
	}

	fullPath := filepath.Join(root, filepath.FromSlash(cleanSlash))

	realRoot, err := filepath.EvalSymlinks(root)
	if err != nil {
		return "", fmt.Errorf("cannot resolve symlinks for trusted root %q: %w", root, err)
	}

	realTarget, err := filepath.EvalSymlinks(fullPath)
	if err != nil {
		if os.IsNotExist(err) {
			return "", fmt.Errorf("artifact %q does not exist on disk", cleanSlash)
		}
		return "", fmt.Errorf("failed resolving symlink for artifact %q: %w", cleanSlash, err)
	}

	rel, err := filepath.Rel(realRoot, realTarget)
	if err != nil || rel == "." || rel == ".." || strings.HasPrefix(rel, "..") || filepath.IsAbs(rel) {
		return "", fmt.Errorf("artifact %q symlink escapes trusted root to %q", cleanSlash, realTarget)
	}

	fi, err := os.Stat(realTarget)
	if err != nil {
		return "", fmt.Errorf("artifact %q stat failed: %w", cleanSlash, err)
	}
	if fi.IsDir() {
		return "", fmt.Errorf("artifact %q is a directory, regular file required", cleanSlash)
	}

	content, err := os.ReadFile(realTarget)
	if err != nil {
		return "", fmt.Errorf("failed to read artifact %q: %w", cleanSlash, err)
	}
	h := sha256.Sum256(content)
	actualSHA := hex.EncodeToString(h[:])

	if workerEvidence != "" {
		reSHA := regexp.MustCompile(`(?i)sha256:([a-f0-9]+)`)
		if sm := reSHA.FindStringSubmatch(workerEvidence); len(sm) > 1 {
			claimed := strings.ToLower(sm[1])
			if !strings.HasPrefix(actualSHA, claimed) && !strings.HasPrefix(claimed, actualSHA) {
				return "", fmt.Errorf("artifact %q hash mismatch: claimed %s, actual %s", cleanSlash, claimed, actualSHA)
			}
		}
	}

	bound := fmt.Sprintf("bound to artifact[%s] sha256=%s (verified on disk)", cleanSlash, actualSHA)
	return bound, nil
}

func formatBoundCheckEvidence(chk CheckResult, evidence TrustedEvidence) string {
	var b strings.Builder
	fmt.Fprintf(&b, "bound to check[%s:%s] ok=%v", chk.Type, chk.Target, chk.OK)
	if evidence.TaskID != "" {
		fmt.Fprintf(&b, " task=%s", evidence.TaskID)
	}
	if evidence.Attempt != "" {
		fmt.Fprintf(&b, " attempt=%s", evidence.Attempt)
	}
	if evidence.HeadSHA != "" {
		fmt.Fprintf(&b, " head=%s", evidence.HeadSHA)
	} else if evidence.TreeSHA != "" {
		fmt.Fprintf(&b, " tree=%s", evidence.TreeSHA)
	}
	if evidence.RawLogSHA != "" {
		fmt.Fprintf(&b, " log_sha256=%s", evidence.RawLogSHA)
	}
	return b.String()
}

func bindCriterionToEvidence(item BriefDoDItem, workerEvidence string, evidence TrustedEvidence) (string, string, bool) {
	hint := strings.TrimSpace(item.VerifierHint)
	var rawTokens []string
	if hint != "" {
		rawTokens = splitVerifierHints(hint)
	} else if item.Description != "" {
		trimmedDesc := strings.TrimSpace(item.Description)
		if isTypeOnlyHint(trimmedDesc) {
			return "UNMET", fmt.Sprintf("type-only hint %q rejected: generic check type without exact target cannot satisfy criterion %s", trimmedDesc, item.ID), false
		}
		rawTokens = []string{trimmedDesc}
	}

	if len(rawTokens) == 0 {
		return "UNMET", fmt.Sprintf("unverified criterion: no passing mechanical check bound to criterion %s (worker prose rejected)", item.ID), false
	}

	var boundChecks []CheckResult
	var boundArtifacts []string

	for _, token := range rawTokens {
		token = strings.TrimSpace(token)
		if token == "" {
			continue
		}

		lowerTok := strings.ToLower(token)
		if strings.HasPrefix(lowerTok, "file:") || strings.HasPrefix(lowerTok, "artifact:") {
			var artPath string
			if strings.HasPrefix(lowerTok, "file:") {
				artPath = strings.TrimSpace(token[5:])
			} else {
				artPath = strings.TrimSpace(token[9:])
			}

			boundArt, err := verifyArtifactSupportingEvidence(artPath, workerEvidence, evidence)
			if err != nil {
				return "UNMET", fmt.Sprintf("artifact verification failed for %s: %v", item.ID, err), false
			}
			boundArtifacts = append(boundArtifacts, boundArt)
			continue
		}

		// Reject type-only hints (e.g. gotest, gotest:, script, diffguard, etc.)
		if isTypeOnlyHint(token) {
			return "UNMET", fmt.Sprintf("type-only hint %q rejected: generic check type without exact target cannot satisfy criterion %s", token, item.ID), false
		}

		var reqType, reqTarget string
		if t, tgt, hasColon := strings.Cut(token, ":"); hasColon {
			reqType = strings.TrimSpace(t)
			reqTarget = strings.TrimSpace(tgt)
			if reqTarget == "" {
				return "UNMET", fmt.Sprintf("type-only hint %q rejected: explicit exact target required for criterion %s", token, item.ID), false
			}
		} else {
			reqTarget = strings.TrimSpace(token)
		}

		var matchedCheck *CheckResult
		for _, chk := range evidence.Checks {
			if reqType != "" {
				if checkTypeMatches(reqType, chk.Type) && exactTargetMatch(reqTarget, chk.Target) {
					c := chk
					matchedCheck = &c
					break
				}
			} else {
				if exactTargetMatch(reqTarget, chk.Target) {
					c := chk
					matchedCheck = &c
					break
				}
			}
		}

		if matchedCheck == nil {
			return "UNMET", fmt.Sprintf("unverified criterion: no executed check matches required hint %q for criterion %s", token, item.ID), false
		}

		if !matchedCheck.OK {
			return "UNMET", fmt.Sprintf("mechanical check failed: %s:%s", matchedCheck.Type, matchedCheck.Target), false
		}

		boundChecks = append(boundChecks, *matchedCheck)
	}

	// Artifact existence/hash alone must NOT substitute a declared matching check!
	// Require exact trusted check binding for every explicit criterion; artifacts are supporting evidence only.
	if len(boundChecks) == 0 {
		return "UNMET", fmt.Sprintf("unverified criterion %s: artifact existence alone cannot substitute declared matching check; exact trusted check binding required", item.ID), false
	}

	var parts []string
	for _, chk := range boundChecks {
		parts = append(parts, formatBoundCheckEvidence(chk, evidence))
	}
	parts = append(parts, boundArtifacts...)

	return "MET", strings.Join(parts, "; "), true
}

// EvaluateDoDMatrixWithEvidence evaluates 1-to-1 coverage of items against reported statuses
// using trusted verification records from this verification invocation (#648).
func EvaluateDoDMatrixWithEvidence(items []BriefDoDItem, reported []DoDItemStatus, checksOK bool, evidence TrustedEvidence) ([]DoDItemStatus, bool) {
	// Rule 1: checksOK == false always rejects unconditionally
	if !checksOK {
		if len(items) == 0 {
			if len(reported) == 0 {
				return nil, false
			}
			matrix := make([]DoDItemStatus, 0, len(reported))
			for _, r := range reported {
				matrix = append(matrix, DoDItemStatus{
					ID:       r.ID,
					Status:   "UNMET",
					Evidence: fmt.Sprintf("unverified worker claim (%s): mechanical checks failed", r.Evidence),
				})
			}
			return matrix, false
		}
		matrix := make([]DoDItemStatus, 0, len(items))
		repMap := make(map[string]DoDItemStatus, len(reported))
		for _, r := range reported {
			repMap[strings.ToUpper(strings.TrimSpace(r.ID))] = r
		}
		for _, item := range items {
			normID := strings.ToUpper(strings.TrimSpace(item.ID))
			ev := "mechanical checks failed (worker self-report rejected)"
			if len(reported) > 0 {
				if _, ok := repMap[normID]; !ok {
					ev = "missing from reported DoD matrix"
				}
			}
			matrix = append(matrix, DoDItemStatus{
				ID:       item.ID,
				Status:   "UNMET",
				Evidence: ev,
			})
		}
		return matrix, false
	}

	// Rule 2: Tasks without explicit criteria (len(items) == 0)
	if len(items) == 0 {
		if len(reported) == 0 {
			// Automated fallback for tasks without explicit criteria passes if actual mechanical checks pass
			return nil, checksOK
		}
		// If worker reported items when no explicit DoD criteria were declared (no-explicit-DoD fallback):
		matrix := make([]DoDItemStatus, 0, len(reported))
		allMET := true
		for i, r := range reported {
			if !strings.EqualFold(r.Status, "MET") {
				r.Status = "UNMET"
				allMET = false
				matrix = append(matrix, r)
				continue
			}
			_, evStr, ok := bindCriterionToEvidence(BriefDoDItem{ID: r.ID, Description: r.Evidence, VerifierHint: r.Evidence}, r.Evidence, evidence)
			if ok {
				r.Status = "MET"
				r.Evidence = evStr
			} else if len(evidence.Checks) > 0 && checksOK {
				// No-explicit-DoD fallback: when tasks lack explicit criteria and mechanical checks pass,
				// bind to verified execution check records
				chk := evidence.Checks[0]
				if i < len(evidence.Checks) {
					chk = evidence.Checks[i]
				}
				r.Status = "MET"
				r.Evidence = formatBoundCheckEvidence(chk, evidence)
			} else {
				r.Status = "UNMET"
				r.Evidence = fmt.Sprintf("unverified worker claim (%s): %s", r.Evidence, evStr)
				allMET = false
			}
			matrix = append(matrix, r)
		}
		return matrix, allMET
	}

	// Rule 3: Explicit DoD criteria (len(items) > 0)
	// Legacy no-record calls fail closed for explicit DoD
	if len(evidence.Checks) == 0 {
		matrix := make([]DoDItemStatus, 0, len(items))
		for _, item := range items {
			matrix = append(matrix, DoDItemStatus{
				ID:       item.ID,
				Status:   "UNMET",
				Evidence: "legacy call without trusted check records fails closed for explicit DoD",
			})
		}
		return matrix, false
	}

	repMap := make(map[string]DoDItemStatus, len(reported))
	for _, r := range reported {
		repMap[strings.ToUpper(strings.TrimSpace(r.ID))] = r
	}

	allOK := true
	matrix := make([]DoDItemStatus, 0, len(items))

	for _, item := range items {
		normID := strings.ToUpper(strings.TrimSpace(item.ID))
		var repStatus *DoDItemStatus
		if len(reported) > 0 {
			if r, ok := repMap[normID]; ok {
				repStatus = &r
			} else {
				// Missing from reported matrix
				allOK = false
				matrix = append(matrix, DoDItemStatus{
					ID:       item.ID,
					Status:   "UNMET",
					Evidence: "missing from reported DoD matrix",
				})
				continue
			}
		}

		if repStatus != nil && !strings.EqualFold(repStatus.Status, "MET") {
			allOK = false
			matrix = append(matrix, DoDItemStatus{
				ID:       item.ID,
				Status:   "UNMET",
				Evidence: fmt.Sprintf("worker reported %s: %s", repStatus.Status, repStatus.Evidence),
			})
			continue
		}

		workerEvidence := ""
		if repStatus != nil {
			workerEvidence = repStatus.Evidence
		}

		// Positive criterion status must bind to trusted verifier-generated check records from THIS invocation
		_, evStr, ok := bindCriterionToEvidence(item, workerEvidence, evidence)
		if ok {
			matrix = append(matrix, DoDItemStatus{
				ID:       item.ID,
				Status:   "MET",
				Evidence: evStr,
			})
		} else {
			allOK = false
			matrix = append(matrix, DoDItemStatus{
				ID:       item.ID,
				Status:   "UNMET",
				Evidence: evStr,
			})
		}
	}

	return matrix, allOK
}

// EvaluateDoDMatrix evaluates 1-to-1 coverage of items against reported statuses.
// Legacy callers without trusted execution check records fail closed for explicit DoD.
func EvaluateDoDMatrix(items []BriefDoDItem, reported []DoDItemStatus, checksOK bool, rawLogSHA string) ([]DoDItemStatus, bool) {
	return EvaluateDoDMatrixWithEvidence(items, reported, checksOK, TrustedEvidence{
		RawLogSHA: rawLogSHA,
	})
}
