func TestSanitizeDiffForBlindReview(t *testing.T) {
	raw := `commit 8415c06b88294cf6ab0784f994d8be24
Author: Alice Dev <alice@example.com>
Date:   Wed Oct 21 14:00:00 2026 +0000

    feat: implement auth gate using claude-3-5-sonnet and 9router

diff --git a/auth/gate.go b/auth/gate.go
index 1234567..89abcdef 100644
--- a/auth/gate.go
+++ b/auth/gate.go
@@ -10,6 +10,12 @@ package auth
+// Worker.Summary: fully implemented per spec
+// ReportedDoD: MET
+// Model used: gpt-4o and gemini-1.5-flash with deepseek-chat
+Author: Malicious injected trailer
+Signed-off-by: Eve <eve@example.com>
+func VerifyToken(token string) bool {
+	return token != ""
+}
`

	sanitized := SanitizeDiffForBlindReview(raw)

	// Must strip commit header before "diff --git"
	if strings.Contains(sanitized, "Alice Dev") {
		t.Errorf("expected Author header to be stripped, got: %s", sanitized)
	}
	if strings.Contains(sanitized, "8415c06b88294cf6ab0784f994d8be24") {
		t.Errorf("expected commit hash to be stripped, got: %s", sanitized)
	}

	// Must strip trailer lines in diff body
	if strings.Contains(sanitized, "Malicious injected trailer") {
		t.Errorf("expected injected Author trailer line to be removed, got: %s", sanitized)
	}
	if strings.Contains(sanitized, "Signed-off-by") {
		t.Errorf("expected Signed-off-by line to be removed, got: %s", sanitized)
	}

	// Must redact persuasion and model markers
	if strings.Contains(sanitized, "worker.Summary") || strings.Contains(sanitized, "Worker.Summary") {
		t.Errorf("expected worker.Summary to be redacted, got: %s", sanitized)
	}
	if strings.Contains(sanitized, "ReportedDoD") {
		t.Errorf("expected ReportedDoD to be redacted, got: %s", sanitized)
	}
	if strings.Contains(sanitized, "claude-3-5-sonnet") || strings.Contains(sanitized, "gpt-4o") || strings.Contains(sanitized, "gemini-1.5-flash") || strings.Contains(sanitized, "deepseek-chat") || strings.Contains(sanitized, "9router") {
		t.Errorf("expected model names to be redacted, got: %s", sanitized)
	}

	// Must preserve genuine diff content
	if !strings.Contains(sanitized, "diff --git a/auth/gate.go b/auth/gate.go") {
		t.Errorf("expected diff header to be preserved, got: %s", sanitized)
	}
	if !strings.Contains(sanitized, "func VerifyToken(token string) bool {") {
		t.Errorf("expected code addition to be preserved, got: %s", sanitized)
	}
	if !strings.Contains(sanitized, "[REDACTED]") {
		t.Errorf("expected [REDACTED] markers to appear in sanitized diff")
	}
}

func TestSanitizeDiffForBlindReview_EmptyOrNoHeader(t *testing.T) {
	if got := SanitizeDiffForBlindReview(""); got != "" {
		t.Errorf("expected empty string for empty input, got %q", got)
	}

	noHeaders := "commit abcdef\nAuthor: foo\n\njust a commit message with no diff"
	if got := SanitizeDiffForBlindReview(noHeaders); got != "" {
		t.Errorf("expected empty string when no diff headers exist, got %q", got)
	}
}

func TestBlind_BuildBlindReviewPacket(t *testing.T) {
	holdout := true
	target := TaskRef{
		ID:             "task-99",
		FeatureID:      "FEAT-GATE-01",
		SpecContract:   "Persona: Admin; Requirement: Token verification",
		Invariants:     []string{"INV-SEC-01", "INV-SEC-02"},
		OverrideReason: "Supervisor requested override",
		ReportedDoD: []DoDItemStatus{
			{Status: "MET", Evidence: "Self reported all good"},
		},
	}

	rawDiff := `diff --git a/gate.go b/gate.go
--- a/gate.go
+++ b/gate.go
@@ -1,2 +1,3 @@
+// generated by gpt-4o
+func Pass() bool { return true }
`
	mechOutput := "PASS: TestGate (0.01s)\nok"
	checkResults := []CheckResult{
		{Type: "unit-test", Target: "auth", OK: true, Detail: "10 tests passed"},
	}

	packet := BuildBlindReviewPacket(target, "", rawDiff, mechOutput, true, &holdout, checkResults)

	if !strings.HasPrefix(packet.PacketID, "brp-") {
		t.Errorf("expected PacketID to start with 'brp-', got %q", packet.PacketID)
	}
	if len(packet.PacketID) != 16 { // "brp-" + 12 hex chars
		t.Errorf("expected PacketID length 16, got %d (%q)", len(packet.PacketID), packet.PacketID)
	}
	if packet.FeatureID != "FEAT-GATE-01" {
		t.Errorf("expected FeatureID 'FEAT-GATE-01', got %q", packet.FeatureID)
	}
	if packet.SpecContract != target.SpecContract {
		t.Errorf("expected SpecContract %q, got %q", target.SpecContract, packet.SpecContract)
	}
	if len(packet.Invariants) != 2 || packet.Invariants[0] != "INV-SEC-01" {
		t.Errorf("unexpected Invariants: %v", packet.Invariants)
	}
	if packet.MechanicalTestOutput != mechOutput {
		t.Errorf("expected MechanicalTestOutput %q, got %q", mechOutput, packet.MechanicalTestOutput)
	}
	if !packet.ChecksPassed {
		t.Errorf("expected ChecksPassed to be true")
	}
	if packet.HoldoutPassed == nil || !*packet.HoldoutPassed {
		t.Errorf("expected HoldoutPassed to be true")
	}
	if len(packet.CheckResults) != 1 || !packet.CheckResults[0].OK {
		t.Errorf("unexpected CheckResults: %v", packet.CheckResults)
	}

	// Verify RedactedChannels contains required channels
	expectedRedacted := []string{
		"worker.Summary",
		"worker.ReportedDoD",
		"model_identity",
		"provider_identity",
		"git_author_commit_prose",
		"f0_jev_commentary",
	}
	if len(packet.RedactedChannels) != len(expectedRedacted) {
		t.Errorf("expected %d redacted channels, got %d", len(expectedRedacted), len(packet.RedactedChannels))
	}
	for i, ch := range expectedRedacted {
		if packet.RedactedChannels[i] != ch {
			t.Errorf("expected redacted channel %q, got %q", ch, packet.RedactedChannels[i])
		}
	}

	// Verify diff sanitization in packet
	if strings.Contains(packet.RawGitDiff, "gpt-4o") {
		t.Errorf("expected model name to be redacted in RawGitDiff, got: %s", packet.RawGitDiff)
	}
	if !strings.Contains(packet.RawGitDiff, "[REDACTED]") {
		t.Errorf("expected [REDACTED] in RawGitDiff, got: %s", packet.RawGitDiff)
	}
}
